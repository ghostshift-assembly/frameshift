[descriptor, record_path, input_path, destination] = System.argv()
{:ok, record} = record_path |> File.read!() |> Conjunct.Wire.decode()
{:ok, inputs} = input_path |> File.read!() |> Conjunct.Wire.decode()
profile = descriptor |> File.read!() |> Conjunct.Wire.blob_id()
{:ok, scene} = Frameshift.Illustration.AssemblyDraft.bundle(profile, record, inputs)
states = Frameshift.Illustration.AssemblyDraft.states(scene)
{:ok, derivation} = Frameshift.Illustration.AssemblyDraft.derive(record, inputs)
if File.exists?(destination), do: raise("destination already exists")
File.mkdir_p!(destination)
File.write!(Path.join(destination, "scene.json"), scene)
File.write!(Path.join(destination, "states.json"), states)
IO.inspect(derivation, label: "Calculated draft / complete installed minimum UNKNOWN")
