[descriptor, record_path, destination] = System.argv()
{:ok, record} = record_path |> File.read!() |> Conjunct.Wire.decode()
profile_digest = descriptor |> File.read!() |> Conjunct.Wire.blob_id()
scene = Frameshift.Illustration.PanelCandidate.bundle(profile_digest, record)
states = Frameshift.Illustration.PanelCandidate.states(scene)
{:ok, enclosure} = Frameshift.Illustration.PanelCandidate.enclosure(record)
if File.exists?(destination), do: raise("destination already exists")
File.mkdir_p!(destination)
File.write!(Path.join(destination, "scene.json"), scene)
File.write!(Path.join(destination, "states.json"), states)
IO.inspect(enclosure, label: "Enclosure dimensions remain source- and design-dependent")
