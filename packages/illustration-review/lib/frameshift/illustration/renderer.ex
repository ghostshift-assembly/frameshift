defmodule Frameshift.Illustration.Renderer do
  @moduledoc """
  Renders the product's verified illustration review as static documentation.

  The renderer consumes DocShell's admitted receipts and hashed local asset
  URLs. It performs no geometry calculation or file access and emits no
  scripts. Each figure preserves the exact state, readouts, warnings, source
  limitations and subject anchors. Print and narrow-screen layouts use the
  same checked content; rendering grants no baseline or physical approval.
  """

  @behaviour DocShell.Presentation.Renderer
  alias DocShell.Presentation.{Asset, Renderer}

  @impl true
  def capabilities do
    %Renderer.Capabilities{
      schema_version: "doc-shell-renderer-capabilities/v1",
      renderer_id: "frameshift/illustration-review",
      renderer_version: "0.1.0",
      output_modes: [:static],
      features: %{"doc-shell/html/v1" => %Renderer.Capability{states: [:fallback], runtime: []}}
    }
  end

  @impl true
  def assets(_, _),
    do: {:ok, [%Asset{path: "assets/review.css", media_type: "text/css", bytes: stylesheet()}]}

  @impl true
  def render_not_found(_, _),
    do:
      {:ok,
       "<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><title>Not found</title></head><body><h1>Not found</h1></body></html>"}

  @impl true
  def render_page(page, context) do
    receipt = page.metadata["artifact_presentation"]
    blocks = Map.new(receipt["blocks"], &{&1["block_id"], &1})
    first = receipt["blocks"] |> hd() |> get_in(["checked_projection", "states"]) |> hd()

    tier =
      if Enum.all?(first["readouts"], &(&1["source"] == "synthetic")),
        do: "Synthetic source",
        else: "Preliminary source candidate"

    figures =
      Enum.map(page.content, fn node -> figure(node, blocks[node["attrs"]["id"]], context) end)

    nav =
      Enum.map(page.content, fn node ->
        [
          "<a href=\"#",
          escape(node["attrs"]["id"]),
          "\">",
          escape(node["meta"]["artifact"]["caption"]),
          "</a>"
        ]
      end)

    style = relative(context.assets["assets/review.css"], context.current_route)

    {:ok,
     [
       "<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width,initial-scale=1\"><title>",
       escape(page.title),
       "</title><link rel=\"stylesheet\" href=\"",
       escape(style),
       "\"></head><body><main><header><p class=\"eyebrow\">FRAMESHIFT · LOCAL TECHNICAL REVIEW</p><h1>",
       escape(first["title"]),
       "</h1><p class=\"intro\">",
       escape(first["description"]),
       "</p><p class=\"status\">",
       tier,
       " · physical checks unknown · procedure completion not recorded</p></header><nav aria-label=\"Illustration states\">",
       nav,
       "</nav>",
       figures,
       "<footer><p>Generated by Conjunct; artifact binding and local export verified by DocShell.</p><p>Inspection grants no baseline approval, operation readiness or device authority.</p><a href=\"",
       escape(relative("/presentation-manifest.json", context.current_route)),
       "\">Presentation bindings</a></footer></main></body></html>"
     ]}
  end

  defp figure(node, receipt, context) do
    block = node["meta"]["artifact"]
    selected = receipt["variant"]
    states = receipt["checked_projection"]["states"]

    state =
      Enum.find(states, fn state -> selected["asset"] == "states/#{state["state"]["id"]}.svg" end) ||
        hd(states)

    url = relative(context.assets[selected["asset"]], context.current_route)

    readouts =
      Enum.map(
        state["readouts"],
        &[
          "<div><dt>",
          escape(&1["label"]),
          "</dt><dd>",
          escape(&1["display"]),
          "<small>",
          escape(&1["source"]),
          " · exact</small></dd></div>"
        ]
      )

    subjects =
      Enum.map(state["subjects"], fn subject ->
        [
          "<li><strong>",
          escape(subject["label"]),
          "</strong><code>",
          escape(subject["id"]),
          "</code><p>",
          escape(subject["limitation"]),
          "</p></li>"
        ]
      end)

    anchors = Enum.map(block["bindings"], &["<span id=\"", escape(&1["anchor"]), "\"></span>"])

    steps =
      Enum.map(state["steps"], fn step ->
        [
          "<li><strong>",
          escape(step["id"]),
          "</strong> ",
          escape(step["wording"]),
          Enum.map(step["warnings"], &["<p class=\"warning\">", escape(&1["wording"]), "</p>"]),
          "<p>No completion is recorded.</p></li>"
        ]
      end)

    [
      "<section id=\"",
      escape(node["attrs"]["id"]),
      "\">",
      anchors,
      "<div class=\"section-heading\"><div><p class=\"eyebrow\">",
      escape(state["state"]["camera"]),
      "</p><h2>",
      escape(block["caption"]),
      "</h2></div><p>",
      escape(block["description"]),
      "</p></div><figure><img src=\"",
      escape(url),
      "\" alt=\"",
      escape(block["description"]),
      "\"><figcaption>State <code>",
      escape(state["state"]["id"]),
      "</code> · selected runtime: none · physical status: ",
      escape(state["physical_status"]),
      "</figcaption></figure><dl class=\"readouts\">",
      readouts,
      "</dl><details><summary>Parts, exact subjects and source limitations</summary><ul class=\"subjects\">",
      subjects,
      "</ul><p>",
      escape(hd(state["subjects"])["limitation"]),
      "</p><p class=\"binding\">Scene <code>",
      escape(receipt["artifact_ref"]),
      "</code></p></details><details class=\"procedure\"><summary>Procedure wording and warnings</summary><ol>",
      steps,
      "</ol></details></section>"
    ]
  end

  defp relative(url, _route), do: url

  defp escape(value),
    do:
      value
      |> to_string()
      |> String.replace("&", "&amp;")
      |> String.replace("<", "&lt;")
      |> String.replace(">", "&gt;")
      |> String.replace("\"", "&quot;")

  defp stylesheet do
    """
    :root{color-scheme:light}*{box-sizing:border-box}body{margin:0;background:#fbfbfa;color:#26262a;font:16px/1.55 system-ui,sans-serif}main{max-width:1240px;margin:auto;padding:56px 40px}header{max-width:850px;margin-bottom:36px}.eyebrow{font-size:12px;letter-spacing:.16em;text-transform:uppercase;color:#737378}h1{font-size:clamp(38px,6vw,72px);line-height:1.04;letter-spacing:-.045em;font-weight:500;margin:20px 0}.intro{max-width:680px;font-size:20px;color:#737378}.status{display:inline-block;padding:9px 14px;background:#e8ede6;font-size:13px}nav{display:flex;flex-wrap:wrap;gap:8px 20px;padding:24px 0;border-top:1px solid #cbd3cc;border-bottom:1px solid #cbd3cc}a{color:#525257;text-underline-offset:4px}section{padding:52px 0;border-bottom:1px solid #cbd3cc}.section-heading{display:grid;grid-template-columns:1fr 1fr;gap:36px;align-items:end}.section-heading p{max-width:520px;color:#737378}h2{font-size:30px;font-weight:500;letter-spacing:-.025em;margin:0}figure{margin:26px 0 0}img{display:block;width:100%;height:auto}figcaption{font-size:13px;color:#737378;margin-top:10px}.readouts{display:flex;gap:48px;flex-wrap:wrap;margin:28px 0}.readouts dt{font-size:13px;color:#737378}.readouts dd{font-size:24px;margin:0}.readouts small{display:block;font-size:12px;color:#737378}details{margin:18px 0}summary{cursor:pointer;padding:12px 0;color:#525257}.subjects{display:grid;grid-template-columns:repeat(3,minmax(0,1fr));gap:12px;list-style:none;padding:0}.subjects code{display:block}code{font-size:12px;overflow-wrap:anywhere}.warning{color:#525257;font-size:14px}.binding{overflow-wrap:anywhere}footer{padding-top:32px;color:#737378;font-size:13px}@media(max-width:650px){main{padding:32px 20px}.section-heading{grid-template-columns:1fr;gap:8px}.subjects{grid-template-columns:1fr}.readouts{gap:24px}section{padding:32px 0}}@media print{nav{display:none}main{padding:0}header{break-after:page}section{break-before:page;border:0;padding:0}details,details>*{display:block}summary{display:n